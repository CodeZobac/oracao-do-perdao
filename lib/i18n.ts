export const messages: Record<Language, Record<MessageKey, string>> = { "pt-BR": pt, en, it };
export type Message = { key: MessageKey; values?: Record<string, string | number> };
export function translate(language: Language, key: MessageKey, values: Record<string, string | number> = {}): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (match, name: string) => String(values[name] ?? match));
}
export function errorKey(cause: unknown, fallback: MessageKey): MessageKey {
  return cause instanceof Error && Object.hasOwn(pt, cause.message) ? cause.message as MessageKey : fallback;
}
